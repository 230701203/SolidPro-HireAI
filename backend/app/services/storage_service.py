"""Private file storage on local disk.

Files are saved under an opaque random name inside UPLOAD_DIR and are only ever served through
authorised API endpoints, so internal paths are never exposed. For production, swap this module
for S3 / Azure Blob (same three functions) and serve via short-lived signed URLs.
"""

import os
import uuid
from pathlib import Path

from app.core.config import get_settings


def _root() -> Path:
    root = Path(get_settings().upload_dir).resolve()
    root.mkdir(parents=True, exist_ok=True)
    return root


def save_bytes(data: bytes) -> str:
    name = uuid.uuid4().hex
    path = _root() / name
    tmp = path.with_suffix(".part")
    with open(tmp, "wb") as fh:
        fh.write(data)
    os.replace(tmp, path)
    return name


def path_for(stored_name: str) -> Path:
    # stored_name is generated by us, but never trust it to build a path.
    if not stored_name.isalnum():
        raise ValueError("invalid stored name")
    p = (_root() / stored_name).resolve()
    if p.parent != _root():
        raise ValueError("invalid stored name")
    return p


def delete(stored_name: str) -> None:
    try:
        path_for(stored_name).unlink(missing_ok=True)
    except ValueError:
        pass
